namespace NUH_PORTAL.Core
{
    // ========================================================================
    //  سياسة الجلسة - رقم واحد يقرأه الخادم والمتصفح معًا.
    //
    //  ⚠️ كانت مهلة الخمول مكتوبة رقمًا داخل الميدلوير، والمتصفح لا يعرفها أصلًا.
    //     النتيجة: الجلسة تنتهي على الخادم والصفحة تبقى مفتوحة أمام المستخدم،
    //     ثم يضغط أي زر بعد نصف ساعة فيُفاجأ برفض بلا سابق إنذار.
    //     الرقم الآن هنا، والواجهة تقرأه من الخادم - فلا يمكن أن يفترقا.
    // ========================================================================
    public static class SessionPolicy
    {
        // مهلة الخمول: تُنهى الجلسة بعدها إن لم يصدر أي نشاط
        public const int IdleTimeoutMinutes = 10;

        // التحذير يظهر قبل النهاية بهذه المدة، مع عدّاد تنازلي
        public const int WarnBeforeSeconds = 120;

        // ====================================================================
        //  ترويسة النداءات الخلفية (Polling) - تعريف واحد يقرأه الخادم والمتصفح.
        //
        //  ⚠️ جرس الإشعارات ينادي /api كل 30 ثانية، وشارة الطلبات كل 60 ثانية،
        //     وكلاهما يعمل والمستخدم تارك الشاشة. لو اعتبرناهما "نشاطًا"
        //     فلن تنتهي الجلسة أبدًا ما دام التبويب مفتوحًا.
        //     كل نداء خلفي يحمل هذه الترويسة، والميدلوير لا يجدّد وقت النشاط لها.
        // ====================================================================
        public const string BackgroundPollHeader = "X-NUH-Poll";

        // ====================================================================
        //  مفتاح ختم آخر نشاط في الكاش.
        //
        //  ⚠️ المفتاح مربوط برقم المستخدم لا برقم الجلسة، يعني بيعيش بعد الخروج.
        //     فأي جلسة جديدة لازم تمسحه أول ما تبدأ، وإلا الختم القديم بيقفلها
        //     من أول نداء API. الصيغة مكتوبة هنا مرة واحدة عشان الميدلوير
        //     وخدمة المصادقة ما يفترقوش في حرف.
        // ====================================================================
        public static string ActivityKey(int userId) => "activity_" + userId;
    }
}
