using NUH_PORTAL.Core.Exceptions;

namespace NUH_PORTAL.Core
{
    // ========================================================================
    //  بوابة الطلب الواحد - تمنع معالجة الطلب نفسه من نداءين متزامنين.
    //
    //  ⚠️ المشكلة التي وُجدت لأجلها:
    //     اعتماد الطلب في مرحلته الأخيرة يمرّ بثلاث خطوات بهذا الترتيب:
    //        (١) قراءة الطلب والتحقق أن مرحلته تسمح بالإجراء
    //        (٢) نداء الأكتف دايركتوري لإنشاء حساب الطالب - وهو نداء شبكة
    //            على وحدة التحكم بالنطاق يستغرق ثوانيَ لا أجزاء من الثانية
    //        (٣) تثبيت الحالة الجديدة وحفظها
    //
    //     والحالة في قاعدة البيانات تبقى كما هي طوال الخطوة (٢). فأي نداء
    //     ثانٍ يصل في تلك الثواني - من مدير آخر فتح الشاشة نفسها، أو من ضغطة
    //     مزدوجة على الزر، أو من إعادة إرسال النموذج - يجد المرحلة صالحة
    //     فيمرّ من الفحص نفسه، **فيُنشأ الحساب مرتين للطالب الواحد**.
    //
    //     وهذا يقع في مسارين لا مسار واحد:
    //        RegistrationService.ApproveAsAdminAsync  (تسجيل الطالب الذاتي)
    //        RequestService.ReviewAsync               (طلبات الموظفين)
    //     ولذلك البوابة هنا لا في أحدهما: نسختان من قفل واحد تفترقان.
    //
    //  ⚠️ لماذا قفل داخل العملية لا قفل في قاعدة البيانات:
    //     التطبيق يعمل بـ hostingModel="inprocess" (راجع web.config)، وهذا
    //     النمط لا يدعم أكثر من عملية عاملة واحدة في IIS أصلًا - فكل نداءات
    //     المنصّة تمرّ على هذه الذاكرة بالضرورة، والقفل هنا يغطّيها جميعًا.
    //
    //     والبديل - قفل في قاعدة البيانات أو مرحلة انتقالية «جارٍ الإنشاء» -
    //     يُدخل عيبًا أسوأ: لو تعطّل التطبيق أثناء نداء الدومين بقي الطلب
    //     محجوزًا في القاعدة ولا أحد يستطيع تحريكه إلا بتعديل يدوي. أما هذه
    //     فتزول بزوال العملية، فلا يبقى طلب عالق أبدًا.
    //
    //     ⚠️ فإن صار للمنصّة يومًا أكثر من خادم، أو تحوّل الاستضافة إلى
    //        outofprocess مع أكثر من عملية عاملة، فهذه البوابة لا تكفي -
    //        عندها تنتقل إلى sp_getapplock أو مرحلة محجوزة في القاعدة.
    //
    //  ⚠️ ولا انتظار في الدخول: الطالب الثاني يُرَدّ فورًا برسالة واضحة بدل
    //     أن تتجمّد شاشته ثوانيَ ثم تصله «المرحلة غير صالحة» - وهي رسالة
    //     كاذبة، لأن المرحلة كانت صالحة والذي منعه هو زميله لا المرحلة.
    // ========================================================================
    public static class RequestGate
    {
        private static readonly object Sync = new();
        private static readonly HashSet<int> InFlight = new();

        // true = دخلت البوابة وعليك استدعاء Exit في finally.
        // false = نداء آخر يعالج هذا الطلب في هذه اللحظة.
        public static bool TryEnter(int requestId)
        {
            lock (Sync) { return InFlight.Add(requestId); }
        }

        // ⚠️ تُستدعى في finally دائمًا - وإلا بقي الطلب مغلقًا حتى إعادة تشغيل
        //    التطبيق. والاستثناء وارد هنا فعلًا: فشل الأكتف دايركتوري يرمي.
        public static void Exit(int requestId)
        {
            lock (Sync) { InFlight.Remove(requestId); }
        }

        // ⚠️ الرسالة موحّدة للمسارين ونصّها هنا لا في كل مسار. وهي محايدة
        //    عن سبب الانشغال: أشهره نداء الأكتف دايركتوري، لكن البوابة تحمي
        //    كل مراحل الطلب لا مرحلة الإنشاء وحدها.
        public static UserFriendlyException Busy() =>
            new("هذا الطلب قيد المعالجة الآن من نداء آخر - انتظر لحظات ثم حدّث الصفحة", 409);
    }
}
