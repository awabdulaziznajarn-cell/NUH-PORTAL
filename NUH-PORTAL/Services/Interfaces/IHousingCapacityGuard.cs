namespace NUH_PORTAL.Services.Interfaces
{
    // ========================================================================
    //  حارس سعة الغرفة - التعريف الوحيد لقاعدة «الغرفة دي تشيل كام».
    //
    //  ⚠️ العمود RoomCapacity كان موجودًا والخريطة بتقرا منه، لكن **مافيش أي
    //     مسار كتابة كان بيسأل عنه**. يعني النظام يعرف إن الغرفة سعتها ٣
    //     ويعرض «مكتملة»، وفي نفس الوقت يقبل رابع وخامس من غير كلمة. النتيجة
    //     إن الخريطة بتتحوّل من أداة تخطيط لتقرير أخطاء.
    //
    //  ⚠️ وحارس واحد لكل المسارات الخمسة (تسجيل الطالب لنفسه، تسجيل المشرف،
    //     تعديل بيانات طالب، نقل السكن، رفع الإكسل) عن قصد: خمس نسخ من نفس
    //     الشرط بتفترق عند أول تعديل، وأول واحدة تُنسى بتفتح الباب كله.
    //
    //  ⚠️ والعدّ **بلا تقسيم أقسام**: مشرف قسم الطلاب لازم يشوف الغرفة مكتملة
    //     حتى لو اللي فيها خارج نطاقه. التقسيم بيخفي بيانات عن العرض، وما
    //     ينفعش يخفي مكانًا مشغولًا عن الحساب - وإلا اتنين اتسكّنوا في نفس السرير.
    // ========================================================================
    public interface IHousingCapacityGuard
    {
        // بيرجّع رسالة الخطأ، أو null لو التسكين مسموح.
        //
        //  excludeStudentId : الطالب اللي بنعدّله أو بننقله - مايتعدّش على نفسه.
        //  allowExceptionSlot: هل المستدعي مسموح له يستخدم المكان الاستثنائي؟
        //     إدارة الإسكان قالت إن المشرف يقدر يزوّد ساكنًا فوق السعة المعتمدة
        //     (RoomCapacityMax). الطالب اللي بيسجّل لنفسه لأ - الاستثناء قرار
        //     إداري لا خانة في فورم.
        //  pendingInSameRoom : أماكن محجوزة في نفس العملية ولسه ما اتحفظتش -
        //     ملف الإكسل بيسكّن عشرة في غرفة واحدة وكلهم لسه مش في الجدول.
        Task<string?> CheckAsync(string? buildingCode, string? floor, string? apartment, string? room,
                                 int? excludeStudentId, bool allowExceptionSlot, int pendingInSameRoom = 0);

        // نفس الفحص بس بيرمي UserFriendlyException بدل ما يرجّع نصّ.
        Task EnsureAsync(string? buildingCode, string? floor, string? apartment, string? room,
                         int? excludeStudentId, bool allowExceptionSlot, int pendingInSameRoom = 0);
    }
}
