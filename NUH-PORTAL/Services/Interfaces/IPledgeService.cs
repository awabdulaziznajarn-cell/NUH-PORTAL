using NUH_PORTAL.DTOs.Registration;

namespace NUH_PORTAL.Services.Interfaces
{
    // ========================================================================
    //  وثيقة التعهّد - المصدر الوحيد في النظام.
    //
    //  ⚠️ ليه خدمة مستقلة: بنية النصّ وبصمته محتاجاها **تلات جهات**:
    //       • صفحة الإقرار في بوابة الطالب - بتعرض البنود وبصمتها
    //       • حفظ التعهّد وقت التقديم - بيجمّد النصّ ويقارن البصمة
    //       • شاشة تفاصيل الطلب - بتعرض التعهّد وتقول هل البنود اتغيّرت بعده
    //     لو كل واحدة بنت النصّ بنفسها، كان ممكن تطلع بصمة مختلفة لنفس البنود
    //     - والبصمة اللي بتختلف بلا سبب مالهاش أي قيمة كدليل.
    // ========================================================================
    public interface IPledgeService
    {
        // البنود المفعّلة دلوقتي + النصّ المجمَّد وبصمته.
        Task<PledgeDocumentDto> GetDocumentAsync();

        // تعهّد طلب بعينه، أو null لو الطلب اتقدّم قبل تفعيل التوثيق.
        Task<PledgeRecordDto?> GetForRequestAsync(int requestId);

        // ⚠️ التحقّق من رمز مطبوع على ورقة. بترجّع null لأي سبب - رمز مش
        //    مقروء، أو رقم طلب مالوش تعهّد، أو بصمة ما طابقتش. **سبب واحد**
        //    عن قصد: أي تفريق بين «الرمز غلط» و«الوثيقة مش موجودة» بيخلّي
        //    الصفحة أداة استعلام لأي حد بيجرّب رموز.
        //
        Task<PledgeVerifyDto?> VerifyDocumentAsync(string? code);

        // ⚠️ نفس القراءة بالظبط، بس بترجّع مفاتيح الملف بدل بيانات مقنّعة -
        //    لشاشة «ملف الطالب» اللي بتفتح الملف كله بعد ما تتحقّق من الرمز.
        //    الاتنين بينادوا نفس المنطق جوّه، فمستحيل رمز يتقبل في واحدة
        //    ويترفض في التانية.
        Task<PledgeDocRefDto?> ResolveDocCodeAsync(string? code);

        // ⚠️ تسجيل طباعة الوثيقة وإرجاع تاريخ الطباعة **من الخادم** كنصّ جاهز.
        //    كان التاريخ من ساعة جهاز اللي بيطبع - وde سطر على ورقة تدخل محضر
        //    تحقيق والنظام مش شاهد عليه. بترجّع null لو الطلب مالوش تعهّد.
        Task<string?> RecordPrintAsync(int requestId);
    }
}
