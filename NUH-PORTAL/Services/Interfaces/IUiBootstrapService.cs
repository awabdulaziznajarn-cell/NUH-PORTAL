namespace NUH_PORTAL.Services.Interfaces
{
    // البيانات اللي كل صفحة MVC بتحقنها في الـ JS (قاموس الترجمة + خريطة القوائم).
    // كانت بتتبني من الأول في كل طلب داخل _Layout.cshtml — يعني قراءة 1380 مورد
    // من الـ resx + أربع استعلامات قاعدة بيانات + serialization، لكل ضغطة على أي
    // صفحة. الخدمة دي بتبنيها مرة وتخزّنها في IMemoryCache.
    public interface IUiBootstrapService
    {
        // قاموس الترجمة للثقافة الحالية — JSON جاهز للحقن جوه <script>.
        // مخزّن للأبد: ملفات الـ resx متجمّعة جوه الـ DLL، فمبتتغيّرش غير مع نشر جديد
        // (والنشر بيعيد تشغيل الـ process فالكاش بيفضى لوحده).
        string GetI18nJson();

        // خريطة القوائم المرجعية (كود → اسم مترجم) — JSON جاهز للحقن.
        // مخزّن 60 ثانية بس: الأدمن بيعدّل الكليات/المباني من شاشة إدارة القوائم،
        // فلازم التعديل يبان بسرعة. الستين ثانية بتشيل تقريبًا كل استعلامات التنقّل
        // العادي بين الصفحات من غير ما تخبّي تعديل الأدمن.
        Task<string> GetLookupMapJsonAsync();

        // نسخة بوابة الطالب: صفحات HTML ثابتة مالهاش لياوت يحقن القاموس، فبتجيبه
        // من نقطة نهاية. بترجع {"i18n":{...},"lookups":{...}} ومفلترة على مفاتيح
        // البوابة بس — عشان ما نبعتش نصوص شاشات الموظفين لزائر غير مسجَّل،
        // وعشان الحجم يبقى معقول على جوال الطالب.
        Task<string> GetPortalBootstrapJsonAsync();
    }
}
