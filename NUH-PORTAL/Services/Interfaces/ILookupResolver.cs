using NUH_PORTAL.Models;

namespace NUH_PORTAL.Services.Interfaces
{
    // بيحوّل أكواد الكلية/القسم/المبنى/المستوى في الطالب لـ FK ids (dual-write مع الكود القديم).
    // بيخلّي أعمدة الـ FK هي المصدر الأساسي للطلاب الجداد بدون ما نكسر التخزين النصي القديم.
    public interface ILookupResolver
    {
        Task ApplyAsync(Student student);
        Task ApplyAsync(IEnumerable<Student> students);

        // ====================================================================
        //  فحص رقم المبنى - التعريف الوحيد في النظام.
        //
        //  ⚠️ كانت القاعدة مكتوبة في مكانين بصيغتين مختلفتين: HashSet في
        //     StudentService، و Regex ‎^(4[0-3]|6[5-9]|70)$‎ في رفع الإكسل.
        //     والمباني **جدول مُدار** من شاشة القوائم المرجعية - فالمدير يضيف
        //     مبنى ٧١، يلاقيه في القايمة المنسدلة (بتقرا من الجدول)، يختاره،
        //     فيترفض عند الحفظ. النظام بيعرض خيارًا ويرفضه هو نفسه.
        //
        //  بيرجّع رسالة الخطأ، أو null لو المبنى سليم (أو الخانة فاضية).
        // ====================================================================
        Task<string?> BuildingCodeErrorAsync(string? code);
    }
}
