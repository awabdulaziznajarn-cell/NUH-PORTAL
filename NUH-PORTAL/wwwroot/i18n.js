var currentLang = localStorage.getItem('uiLanguage') || 'ar';

function t(key) {
  var dict = LANG_DATA[currentLang] || LANG_DATA.ar;
  return dict[key] != null ? dict[key] : (LANG_DATA.ar[key] || key);
}

function __baseSetLang(l) {
  currentLang = l;
  localStorage.setItem('uiLanguage', l);
  var root = document.getElementById('html-root') || document.documentElement;
  root.setAttribute('lang', l);
  root.setAttribute('dir', l === 'ar' ? 'rtl' : 'ltr');
  var btnAr = document.getElementById('btn-ar');
  var btnEn = document.getElementById('btn-en');
  if (btnAr) btnAr.classList.toggle('active', l === 'ar');
  if (btnEn) btnEn.classList.toggle('active', l === 'en');
  document.querySelectorAll('[data-ar]').forEach(function(el) {
    var newText = l === 'ar' ? el.dataset.ar : el.dataset.en;
    if (el.children.length === 0) {
      el.textContent = newText;
    } else {
      var child = el.firstChild;
      if (child && child.nodeType === Node.TEXT_NODE) child.textContent = newText;
    }
  });
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-value]').forEach(function(el) {
    el.value = t(el.dataset.i18nValue);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    el.title = t(el.dataset.i18nTitle);
  });
  var d = document.getElementById('dateNow');
  if (d) {
    var now = new Date();
    d.textContent = l === 'ar'
      ? now.toLocaleDateString('ar-SA', {weekday:'long', year:'numeric', month:'long', day:'numeric'})
      : now.toLocaleDateString('en-US', {weekday:'long', year:'numeric', month:'long', day:'numeric'});
  }
  var sidebarName = document.getElementById('sidebar-user-name');
  var sidebarRole = document.getElementById('sidebar-user-role');
  if (sidebarName) {
    try {
      var u = JSON.parse(localStorage.getItem('staffUser') || localStorage.getItem('studentUser') || '{}');
      sidebarName.textContent = u.full_name || u.username || '';
      if (sidebarRole) sidebarRole.textContent = u.role || '';
    } catch (e) {
      // Corrupted localStorage data — silently ignore
    }
  }
}

var onLanguageChange = null;

function setLang(l) {
  try { __baseSetLang(l); } catch (e) { console.warn('__baseSetLang error:', e); }
  if (typeof onLanguageChange === 'function') { try { onLanguageChange(l); } catch (e) { console.warn('onLanguageChange error:', e); } }
}

// For pages using applyLang pattern (login pages)
function applyLang(l) {
  setLang(l);
  // Update document level items
  document.title = t('appTitle');
}

