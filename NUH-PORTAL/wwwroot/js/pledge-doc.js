                  'تاريخ الطباعة' + ': <span class="pl-sh-printed"></span></span>';

    // ============================================================================
    //  «طُبعت بواسطة» - مين أخرج النسخة دي.
    //
    //  ⚠️ الورقة بتتطبع وقت التحقيق وبتدخل المحضر، والسؤال «مين طبعها؟» بيتسأل
    //     فعلًا. الأثر الرسمي في سجل العمليات (pledge_printed)، والسطر ده
    //     بيخلّي الإجابة مقروءة على الورقة نفسها بلا رجوع للنظام.
    //
    //  ⚠️ الاسم وبس - بلا اسم المستخدم وبلا الإدارة:
    //       • اسم المستخدم موجود في العلامة المائية على نفس الورقة، وتكراره
    //         هنا بيطوّل السطر بلا أي معلومة جديدة.
