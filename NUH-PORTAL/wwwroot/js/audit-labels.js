// ============================================================================
//  أسماء الإجراءات وأسماء الحقول في سجل العمليات - التعريف الوحيد.
//
//  ⚠️ سجل العمليات كان يطبع ما في قاعدة البيانات حرفيًّا: اسم الإجراء
//     «faculty_occupant_updated» واسم الحقل «NationalId» - نصّ إنجليزي خام
//     في شاشة عربية. والموظف الذي يُطلب منه تقرير مساءلة يقرأ أسماء أعمدة
//     قاعدة بيانات لا بيانات.
//
//     والترجمة كانت ستُكتب في كل شاشة تعرض سجلًّا: شاشة سجل العمليات، ونافذة
//     سجل الوحدة في سكن أعضاء هيئة التدريس. فتُترجم في إحداهما وتبقى خامة في
//     الأخرى. هنا تُترجم مرة واحدة.
//
//  المفاتيح في SharedResource: aud_action_<الإجراء> و aud_field_<الحقل>.
//  المفتاح المفقود يُرجع الاسم الخام لا المفتاح: نصٌّ ناقص أقلّ ضررًا من
//  «aud_field_Xyz» على الشاشة.
// ============================================================================
var NuhAudit = (function () {
  'use strict';

  // نفس مصدر t() في i18n.js: القاموس المحقون من الـ .resx في _Layout.
  // نقرأ منه مباشرة كي تعمل هذه الوحدة في الشاشات التي لا تحمّل i18n.js.
  function dict() {
    return (typeof window !== 'undefined' && window.__I18N) ? window.__I18N : {};
  }

  // ⚠️ المفتاح يُصغَّر قبل البحث، والمفاتيح في الـ .resx صغيرة كلها.
  //
  //    السبب ليس التبسيط: MSBuild يقارن أسماء موارد الـ .resx تجاهلًا لحالة
  //    الأحرف، فمفتاحا "aud_field_Status" و"aud_field_status" يُعدّان تكرارًا
  //    ويُهمَل أحدهما بتحذير MSB3568 - فيظهر الحقل خامًا على الشاشة رغم أن
  //    مفتاحه مكتوب في الملف. وأسماء الحقول في قاعدة البيانات تأتي بالصيغتين:
  //    "national_id" من سجلات الطلاب و"NationalId" من سكن أعضاء هيئة التدريس.
  //    التصغير هنا يجعل الصيغتين تصلان إلى مفتاح واحد لا يتصادم.
  function look(prefix, name) {
    if (!name) return '';
    var v = dict()[prefix + String(name).toLowerCase()];
    return (v == null || v === '') ? name : v;
  }

  function actionText(action) { return look('aud_action_', action); }
  function fieldText(field) { return look('aud_field_', field); }

  // القيمة كما تُعرض: الفارغ يُكتب «(فارغ)» لا يُترك بياضًا، لأن الفرق بين
  // «كانت فارغة فمُلئت» و«لم تتغيّر» هو جوهر السطر.
  function valueText(v) {
    if (v == null || v === '') {
      var e = dict()['aud_emptyValue'];
      return e || '-';
    }
    return String(v);
  }

  return { actionText: actionText, fieldText: fieldText, valueText: valueText };
})();
