// ==========================================================================
//  esc.js — تهريب النصوص قبل حقنها في HTML. التعريف الوحيد في النظام.
//
//  ⚠️ ليه الملف ده موجود:
//     نفس الدالة كانت متكرّرة ١٣ مرة: في التخطيط، وفي خمس شاشات، وفي سبع
//     ملفات جافاسكريبت — مرة باسم esc ومرة escHtml ومرة escOpt ومرة hmEsc،
//     ومرة مكتوبة بـ replace متسلسلة ومرة بـ [&<>"'] وجدول تبديل. كلها
//     بتعمل نفس الحاجة بالظبط.
//
//     والتكرار مكانش تجميليًّا: تلات نسخ منهم كانت **أضعف** من الباقي، ناقصة
//     تهريب علامة الاقتباس المفردة ('):
//
//        wwwroot/js/reports-page.js
//        wwwroot/js/request-details-page.js
//        wwwroot/lookups.js   (escOpt)
//
//     والاتنين الأولانيين كانوا معرّفين باسم escHtml في النطاق العام — يعني
//     كانوا **بيدهسوا** نسخة التخطيط القوية على الصفحات اللي بتحمّلهم. فشاشة
//     التقارير وشاشة تفاصيل الطلب كانتا شغّالتين بالنسخة الناقصة، ومحدّش
//     يقدر يشوف ده من الشاشة نفسها.
//
//     وده بيفرق فعلًا: أي قيمة بتتحقن جوّه خاصية متكتوبة بعلامة مفردة
//     (title='...' أو onclick="f('...')") تقدر تخرج من الخاصية بعلامة واحدة.
//     وأسماء الطلاب والملاحظات وأسماء الوحدات كلها بتتحقن في خصائص زي دي.
//
//  ⚠️ الترتيب جوّه الدالة مقصود: & الأول. لو اتأخرت كانت هتعيد تهريب النواتج
//     نفسها (&lt; تبقى &amp;lt;) فالنص يظهر للمستخدم بالرموز الخام.
//
//  ⚠️ ولازم يتحمّل قبل أي ملف تاني بيستخدمه: مكانه أول السكربتات المشتركة في
//     Views/Shared/_Layout.cshtml، وفي الصفحات المستقلة (بوابة الطالب) قبل
//     الملفات اللي بتناديه.
// ==========================================================================
function escHtml(v) {
  return String(v == null ? '' : v)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// ==========================================================================
//  escNum - رقم مركّب (رقم طلب، رمز، معرّف) جوّه نصّ عربي.
//
//  ⚠️ ليه محتاج تغليف أصلًا:
//     «2026-000031» جوّه فقرة عربية كان بيتقرا **مقلوب**: «000031-2026».
//     ودي مش مشكلة في الكود ولا في قاعدة البيانات - القيمة المخزّنة صح.
//     دي خوارزمية الاتجاه في المتصفح (Unicode Bidi):
//
//       ١. الأرقام اللي قبلها نصّ عربي بتتحوّل من European Number
//          لـ Arabic Number.
//       ٢. الشرطة بتوصل رقمين أوروبيين في وحدة واحدة، لكنها **مابتوصلش**
//          رقمين عربيين - فبتفضل محايدة.
//       ٣. المحايد بياخد اتجاه الفقرة = يمين لشمال.
//
//     فالنتيجة: «2026» و«000031» بيبقوا مقطعين منفصلين مرتّبين من اليمين
//     للشمال، والعين بتقراهم بالعكس. الرقم اللي فيه حروف (BRQ-000006،
//     NUH-1000-ZQ10) بيسلم لأن الحرف اتجاهه قويّ - فالمشكلة بتظهر في
//     الأرقام الصافية بس، وده اللي خلّاها تعدّي.
//
//  ⚠️ ‏<bdi> لا <span>: بتعزل الرقم عن اتجاه اللي حواليه، والعزل ده هو
//     الحلّ. و dir="ltr" صريحة لأن dir الافتراضية «auto» بتدوّر على أول
//     حرف قويّ - ومفيش، فبتقع على افتراضي ممكن يختلف بين متصفحات.
//
//  ⚠️ الحلّ ده CSS-free بالقصد: الحاويات اللي بتعرض أرقام كتير في النظام،
//     كل واحدة كانت بتحلّها لوحدها بـ direction:ltr في الـ CSS بتاعها
//     (‎.rq-num‎ في الرئيسية حلّاها، و‎.info-value‎ لأ) - فالشاشة اللي
//     الكاتب نسيها بتطلع مقلوبة ومحدّش ياخد باله. الدالة دي بتخلّي
//     الصحّة في القيمة نفسها مهما كانت الحاوية.
// ==========================================================================
function escNum(v) {
  return '<bdi dir="ltr">' + escHtml(v == null || v === '' ? '-' : v) + '</bdi>';
}
