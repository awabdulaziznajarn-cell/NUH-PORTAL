namespace NUH_PORTAL.Models.Enums
{
    // حالة تطابق بيانات الوحدة بين النظام والدومين.
    // ⚠️ Pending مش معناها «مانكتبناش»، معناها «كتبنا في النظام والكتابة في
    //    الدومين ما تمّتش». الفرق مهم: البيانات عندنا سليمة والإجراء متسجّل،
    //    اللي ناقص هو الدفع للدومين — فبنعيد المحاولة، مش بندخّل البيانات تاني.
    public enum FacultyUnitSyncState
    {
        Synced = 1,   // آخر كتابة نجحت
        Pending = 2,  // متسجّلة عندنا ولسه ما اتكتبتش في الدومين
        Failed = 3    // الدومين رفض — السبب في LastSyncError
    }
}
