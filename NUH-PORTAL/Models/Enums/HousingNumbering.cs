namespace NUH_PORTAL.Models.Enums
{
    // ========================================================================
    //  أسلوب ترقيم الشقق والغرف داخل المبنى - مؤكَّد مع إدارة الإسكان.
    //
    //  البنية واحدة في كل المباني (الأرضي + ٤ أدوار، ٤ شقق في الدور، ٤ غرف
    //  في الشقة). اللي بيختلف هو **الترقيم**، والاختلاف ده حقيقي في السكن
    //  نفسه - مش تفصيلة عرض:
    //
    //    Continuous (سكن الطلاب): الترقيم متّصل عبر المبنى كله.
    //        الأرضي: شقق ١-٤   وغرفها ١-١٦
    //        الدور ١: شقق ٥-٨   وغرفها ١٧-٣٢ ... وهكذا لحد غرفة ٨٠.
    //        يعني رقم الغرفة وحده بيحدّد شقتها ودورها.
    //
    //    PerFloor (سكن الطالبات): الترقيم بيبدأ من أول في كل دور.
    //        كل دور: شقق ١-٤، وكل شقة غرفها ١-٤.
    //        يعني «شقة ٢ غرفة ٣» مالهاش معنى من غير الدور - في المبنى خمس
    //        غرف بنفس الوصف ده، واحدة في كل دور.
    //
    //  ⚠️ ولذلك التحقّق مختلف: في Continuous رقم الشقة بيحدّد الدور فبنقارن
    //     الاتنين، وفي PerFloor الدور **لازم** يتخزّن ومافيش حاجة تستنتجه.
    // ========================================================================
    public enum HousingNumbering
    {
        Continuous = 1,
        PerFloor = 2
    }
}
